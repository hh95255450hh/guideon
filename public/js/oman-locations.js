/**
 * Helper to populate a <select> with governorates (first dropdown).
 * @param {HTMLSelectElement} select
 * @param {string} [placeholderEn]
 * @param {string} [placeholderAr]
 */
window.populateGovernorates = function (select, placeholderEn = 'All Governorates', placeholderAr = 'كل المحافظات') {
  if (!select) return;
  const isAr = (document.documentElement.lang || 'en').startsWith('ar');
  select.innerHTML = `<option value="">${isAr ? placeholderAr : placeholderEn}</option>` +
    window.OMAN_LOCATIONS.map(g =>
      `<option value="${g.governorateEn}">${isAr ? g.governorateAr : g.governorateEn}</option>`
    ).join('');
};

/**
 * Populate a <select> with wilayats based on the selected governorate.
 * Pass null to show ALL wilayats from every governorate.
 * @param {HTMLSelectElement} select
 * @param {string|null} governorateEn
 */
window.populateWilayats = function (select, governorateEn = null, placeholderEn = 'All Wilayats', placeholderAr = 'كل الولايات') {
  if (!select) return;
  const isAr = (document.documentElement.lang || 'en').startsWith('ar');

  let wilayats = [];
  if (governorateEn) {
    const g = window.OMAN_LOCATIONS.find(x => x.governorateEn === governorateEn);
    if (g) wilayats = g.wilayats;
  } else {
    wilayats = window.OMAN_LOCATIONS.flatMap(g => g.wilayats);
  }

  select.innerHTML = `<option value="">${isAr ? placeholderAr : placeholderEn}</option>` +
    wilayats.map(w =>
      `<option value="${w.en}">${isAr ? w.ar : w.en}</option>`
    ).join('');
};

/**
 * Wire two <select>s as a cascading governorate → wilayat pair.
 * @param {HTMLSelectElement} govSelect
 * @param {HTMLSelectElement} wilSelect
 */
window.linkGovernorateWilayat = function (govSelect, wilSelect) {
  if (!govSelect || !wilSelect) return;
  populateGovernorates(govSelect);
  populateWilayats(wilSelect, null);
  govSelect.addEventListener('change', () => {
    populateWilayats(wilSelect, govSelect.value || null);
  });
};
