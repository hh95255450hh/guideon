/**
 * Populate a <select> with country codes.
 */
window.populateCountryCodes = function (select, defaultCode = 'OM') {
  if (!select) return;
  const isAr = (document.documentElement.lang || 'en').startsWith('ar');
  select.innerHTML = window.COUNTRY_CODES.map(c =>
    `<option value="${c.dial}" data-code="${c.code}" ${c.code === defaultCode ? 'selected' : ''}>${c.flag} ${isAr ? c.ar : c.name} (${c.dial})</option>`
  ).join('');
};

/**
 * Combine the country code and the local number into a single E.164-like
 * string. Strips any leading 0 from the local part (common Oman habit).
 */
window.buildPhoneE164 = function (dialCode, localNumber) {
  if (!dialCode) return localNumber || '';
  let local = String(localNumber || '').replace(/[\s\-()+]/g, '');
  if (local.startsWith('0')) local = local.slice(1);
  return `${dialCode} ${local}`.trim();
};
